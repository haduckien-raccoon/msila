"""Build the fixed MS-ILA Day-3 Overfit-16 architecture-QA dataset.

Scope
-----
This module implements ONLY Day-3 Task 7 (Overfit-16 dataset construction).
It does not implement loss, optimizer, trainer, visualization, checkpointing,
resume, integration QA, or Day-3 reporting.

Scientific purpose
------------------
Overfit-16 is a deliberately tiny, deterministic dataset used to answer one
engineering question:

    Can the current architecture memorize a controlled 16-sample problem?

It is NOT a benchmark set and MUST NOT be used to claim generalization,
AU-PRO_0.05 performance, or realism of synthetic defects.

Locked composition
------------------
- 16 distinct source images selected deterministically from a normal-only pool.
- 8 true normal samples (unchanged RGB image + all-zero mask).
- 8 controlled synthetic-anomaly samples generated by Task-6
  ``SyntheticAnomalyGenerator``.

The synthetic perturbation is applied BEFORE any Local/Context construction,
DINO normalization, DINOv3 extraction, feature cache, adapter, fusion, or
decoder stage. This prevents the invalid supervision case where a normal
feature tensor is paired with a synthetic anomaly mask that is not present in
the input image.

Output layout
-------------
<output_root>/
    manifest.json
    images/
        ov16_00_normal.png
        ...
        ov16_15_anomaly.png
    masks/
        ov16_00_normal.png
        ...
        ov16_15_anomaly.png

The manifest stores source provenance, deterministic seeds, exact output pixel
hashes, Task-6 metadata, and dataset-level descriptive statistics.
"""

